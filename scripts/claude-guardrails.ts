#!/usr/bin/env bun
/**
 * DeckTerm guardrails: a Claude Code PreToolUse hook for this repository.
 *
 * Wired in .claude/settings.json for Bash and file-edit tools. It replaces the
 * four hookify rule files that stopped loading when the hookify plugin was
 * turned off (24 Oct 2026): three rules block, one only warns. The patterns are
 * the hookify ones, except that the warning also matches `systemctl --user`
 * (both DeckTerm services are user units, so the old pattern never matched).
 * Flags follow hookify's Python re.search: case-insensitive, `.` stops at a
 * newline. The prod-port rule is anchored per line (^ with m), which matches
 * the same commands as an unanchored search but stays linear on long input.
 *
 * Protocol: read the hook input (JSON) on stdin. Block = exit 2 with the reason
 * on stderr (Claude Code shows it to the model and skips the tool call).
 * Warn = exit 0 with hookSpecificOutput.additionalContext. Allow = exit 0, no
 * output. Unparsable input is allowed, so a broken input never wedges a session.
 * Pure and deterministic: no network, no files, no environment.
 */

type Action = "block" | "warn" | "allow";

export interface Verdict {
  action: Action;
  rule?: string;
  message?: string;
}

interface Rule {
  name: string;
  action: Exclude<Action, "allow">;
  /** Which input field the pattern is matched against. */
  field: "command" | "file_path";
  pattern: RegExp;
  message: string;
}

const BASH_TOOLS = new Set(["Bash"]);
const FILE_TOOLS = new Set(["Edit", "Write", "MultiEdit", "NotebookEdit"]);

export const RULES: Rule[] = [
  {
    name: "block-deckterm-prod-port-tests",
    action: "block",
    field: "command",
    pattern:
      /^(?=.*(playwright|npm\s+(run\s+)?test|bun\s+test|curl|npx))(?=.*(localhost:4173|127\.0\.0\.1:4173|PORT=4173|--port\s+4173))/im,
    message:
      "Blocked DeckTerm production-port test: tests must run against the development port 4174, never the production port 4173. Use http://localhost:4174 or the dev service deckterm-dev.service.",
  },
  {
    name: "block-deckterm-vendor-edits",
    action: "block",
    field: "file_path",
    pattern: /(^|\/)web\/vendor\//i,
    message:
      "Blocked vendor file edit: do not modify web/vendor/ files directly. Update the source dependency or local integration code instead (vendor/codemirror.js is regenerated by scripts/build-codemirror-vendor.js).",
  },
  {
    name: "block-destructive-commands",
    action: "block",
    field: "command",
    pattern:
      /(git\s+(reset\s+--hard|clean\s+-f[dDx]*|checkout\s+--)|rm\s+-rf\s+(\/(\s|$)|~(\/|\s|$)|\.(\s|$)|\/home\/deploy(\/|\s|$)|\/home\/deploy\/deckterm_dev(\/|\s|$)|\/home\/deploy\/deckterm(\/|\s|$))|chmod\s+(-R\s+)?777)/i,
    message:
      "Blocked destructive command: do not run destructive git or filesystem cleanup commands from the DeckTerm workspace unless the user explicitly asked for that exact operation. Use a targeted command instead, or ask for confirmation with the exact path and rollback impact.",
  },
  {
    name: "warn-deckterm-manual-prod-deploy",
    action: "warn",
    field: "command",
    pattern:
      /(systemctl\s+(--user\s+)?(restart|start|stop)\s+deckterm\.service|DEPLOY_ROOT=\/home\/deploy\/apps\/deckterm\/prod|\/home\/deploy\/apps\/deckterm\/prod|bun\s+run\s+start)/i,
    message:
      "DeckTerm production reminder: do not manually deploy production unless explicitly requested. The normal push-to-main flow must be verified through the Deploy Main GitHub Actions workflow before claiming production is updated.",
  },
];

function fieldValue(input: Record<string, unknown>, field: Rule["field"]): string | null {
  const tool = typeof input.tool_name === "string" ? input.tool_name : "";
  const args = input.tool_input;
  if (!args || typeof args !== "object") return null;
  const a = args as Record<string, unknown>;
  if (field === "command") {
    return BASH_TOOLS.has(tool) && typeof a.command === "string" ? a.command : null;
  }
  if (!FILE_TOOLS.has(tool)) return null;
  const path = typeof a.file_path === "string" ? a.file_path : a.notebook_path;
  return typeof path === "string" ? path : null;
}

/** Decide one tool call. A block wins over a warning; the first match of each kind is reported. */
export function evaluate(input: unknown): Verdict {
  if (!input || typeof input !== "object") return { action: "allow" };
  const record = input as Record<string, unknown>;
  let warning: Verdict | null = null;
  for (const rule of RULES) {
    const value = fieldValue(record, rule.field);
    if (value === null || !rule.pattern.test(value)) continue;
    if (rule.action === "block") return { action: "block", rule: rule.name, message: rule.message };
    warning ??= { action: "warn", rule: rule.name, message: rule.message };
  }
  return warning ?? { action: "allow" };
}

if (import.meta.main) {
  let input: unknown = null;
  try {
    input = JSON.parse(await Bun.stdin.text());
  } catch {
    process.exit(0);
  }
  const verdict = evaluate(input);
  if (verdict.action === "block") {
    process.stderr.write(`[${verdict.rule}] ${verdict.message}\n`);
    process.exit(2);
  }
  if (verdict.action === "warn") {
    process.stdout.write(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          additionalContext: `[${verdict.rule}] ${verdict.message}`,
        },
      }) + "\n",
    );
  }
  process.exit(0);
}
